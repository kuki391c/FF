local function updateMovingLED()
    if not LEDBorder.Visible then return end
    local size = LEDBorder.AbsoluteSize
    local w, h = size.X, size.Y
    if w <= 0 or h <= 0 then return end

    local t = (tick() * 120) % (2 * (w + h - 12))
    local x, y
    local margin = 6
    local top = margin
    local right = w - margin
    local bottom = h - margin

    if t < (right - margin) then
        x, y = margin + t, top
    elseif t < (right - margin) + (bottom - top) then
        x, y = right, top + (t - (right - margin))
    elseif t < 2 * (right - margin) + (bottom - top) then
        x, y = right - (t - ((right - margin) + (bottom - top))), bottom
    else
        x, y = margin, bottom - (t - (2 * (right - margin) + (bottom - top)))
    end

    LEDRunner.Position = UDim2.fromOffset(x, y)
    if math.abs(y - top) < 2 or math.abs(y - bottom) < 2 then
        LEDRunner.Size = UDim2.fromOffset(50, 4)
    else
        LEDRunner.Size = UDim2.fromOffset(4, 50)
    end
end

